"""Compute data-quality and coverage statistics from the processed tables and write
research/data_quality_report.md. Every number in that report is generated here."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common import INTERIM, PROCESSED, RESEARCH, TODAY  # noqa: E402

TYPES = ["Bank or Thrift", "Bank Holding Company", "Credit Union", "Loan Fund", "Venture Capital Fund"]


def pct(n, d):
    return f"{n / d * 100:.1f}%" if d else "n/a"


def md(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r.values) + " |")
    return "\n".join(lines)


def main() -> None:
    m = pd.read_csv(PROCESSED / "cdfi_master.csv", low_memory=False)
    xw = pd.read_csv(INTERIM / "crosswalks" / "crosswalk_long.csv", dtype={"id_value": str})
    aw = pd.read_csv(PROCESSED / "cdfi_awards.csv")
    pub = json.loads((INTERIM / "normalized_treasury" / "treasury_published_totals.json").read_text())
    n = len(m)

    # Coverage by type
    rows = []
    for ty in TYPES:
        g = m[m.institution_type == ty]
        k = len(g)
        rows.append({
            "Institution type": ty, "N": k,
            "RSSD on Treasury list": pct(g.rssd_id.notna().sum(), k),
            "Matched to FDIC (self)": pct(g.fdic_cert.notna().sum(), k),
            "Matched to FDIC (subsidiaries)": pct(g.fdic_cert_subsidiaries.notna().sum(), k),
            "Matched to NCUA": pct(g.ncua_charter.notna().sum(), k),
            "EIN (IRS BMF)": pct(g.ein.notna().sum(), k),
            "Regulatory assets (2026-06-30)": pct(g.has_regulatory_assets.sum(), k),
            "Any assets (incl. IRS)": pct(g.has_assets.sum(), k),
            "Lending mix": pct(g.has_lending_mix.sum(), k),
            "Primary focus": pct(g.has_primary_focus.sum(), k),
            "Members": pct(g.members.notna().sum(), k),
            "Branch footprint": pct(g.branch_count.notna().sum(), k),
            "HQ county FIPS": pct(g.hq_county_fips.notna().sum(), k),
            "≥1 linked CDFI Fund award": pct((g.award_count > 0).sum(), k),
        })
    cov = pd.DataFrame(rows)

    # Match methods
    mm = (xw[xw.id_system.isin(["FDIC_CERT", "NCUA_CHARTER", "EIN"])]
          .groupby(["institution_type", "id_system", "relationship", "match_method", "match_confidence"], dropna=False)
          .cdfi_id.nunique().reset_index(name="CDFIs"))

    review = xw[xw.manual_review_required]
    rev_by = review.groupby(["institution_type", "match_method"]).cdfi_id.nunique().reset_index(name="CDFIs flagged")

    dep = m[m.institution_type.isin(["Bank or Thrift", "Bank Holding Company", "Credit Union"])]
    unmatched_dep = dep[dep.regulator_match_status != "matched_with_current_financials"]
    unm_reason = xw[xw.cdfi_id.isin(unmatched_dep.cdfi_id) & xw.id_system.isin(["FDIC_CERT", "NCUA_CHARTER"])]
    unm_tab = (unm_reason.sort_values("relationship").drop_duplicates("cdfi_id")
               .assign(reason=lambda d: d.review_reason.fillna("").str.slice(0, 120))
               .groupby(["institution_type", "match_method"]).cdfi_id.nunique().reset_index(name="CDFIs"))

    focus = pd.crosstab(m.institution_type, m.primary_lending_focus.fillna("(missing)")).reset_index()
    conf = pd.crosstab(m.institution_type, m.primary_focus_confidence.fillna("(missing)")).reset_index()

    linked = aw.cdfi_id.notna()
    aw_tab = aw.groupby("award_match_method", dropna=False).size().reset_index(name="award rows")

    pub_types = {k: v for k, v in pub["published_by_type"].items() if k != "TOTAL"}
    by_type_pub = pd.DataFrame({"Treasury published": pd.Series(pub_types),
                                "Collected": m.institution_type.value_counts()}).fillna(0).astype(int)
    by_type_pub.loc["TOTAL"] = by_type_pub.sum()
    by_type_pub = by_type_pub.reset_index(names="Type")
    tl = pd.read_csv(INTERIM / "normalized_treasury" / "treasury_cert_list.csv")

    dup = m[m.dup_rssd_in_list]
    shared = m[m.shares_website_with.notna()]
    bhc_excl = m[~m.include_in_market_totals]

    txt = f"""# Data Quality Report — U.S. Certified CDFI Landscape

_Generated by `scripts/analyze/data_quality_report.py` on {TODAY}. All figures are computed from
`data/processed/` and `data/interim/crosswalks/`; none are estimated._

## 1. Universe

* Source: CDFI Fund *List of Certified CDFIs*, as of **{m.source_as_of_date.iloc[0]}** (retrieved {m.retrieval_date.iloc[0]}).
* Certified CDFIs collected: **{n:,}** (Treasury-published total: {pub.get('published_total')}; Native CDFIs:
  {int(m.native_cdfi.sum())} collected vs {pub.get('published_native_total')} published).
* One row per Treasury list row; internal `cdfi_id`s are stable across runs (registry: `data/reference/cdfi_id_registry.csv`).

{md(by_type_pub)}

Treasury labels "Venture Capital" (7) and "Venture Capital Fund" (2) were merged into
"Venture Capital Fund"; the original label is kept in `institution_type_as_listed`.

## 2. Coverage by institution type

{md(cov)}

Notes:
* BHCs are matched to their FDIC-insured **subsidiary banks** (via FDIC `RSSDHCR`); their financials are the
  sum over subsidiaries. {len(bhc_excl)} BHCs have only subsidiaries that are themselves separately certified and
  are flagged `include_in_market_totals = False` to prevent double counting.
* Loan-fund/VC "assets" come only from the IRS EO BMF (latest Form 990 on file; tax periods vary) and are not
  comparable in timing or definition to Call Report assets. No lending mix is publicly available for them.

## 3. Crosswalk match methods (FDIC / NCUA / EIN)

{md(mm)}

## 4. Records flagged for manual review

Total CDFIs with at least one review-flagged crosswalk row: **{review.cdfi_id.nunique()}** (details in
`research/unresolved_matches.csv`).

{md(rev_by)}

## 5. Depository CDFIs without current regulatory financials

{len(unmatched_dep)} of {len(dep)} banks/BHCs/credit unions have no 2026-06-30 regulatory financials attached.

{md(unm_tab)}

Main reasons:
* `not_in_ncua_scope`: Puerto Rico *cooperativas de ahorro y crédito* are insured/supervised by COSSEC, not
  NCUA, so no 5300 Call Report exists. These are listed by Treasury as "Credit Union".
* `rssd_exact_inactive` / `rssd_holding_company_inactive` / `absent_from_latest_ncua`: the institution merged or
  closed after certification; the Treasury list appears stale for these entries. Successor institutions are
  recorded (relationship `merger_successor`) but their financials are **not** attributed.
* `unmatched` / `unmatched_see_probable_subsidiary` BHCs: the BHC RSSD is not a top-tier holding company in
  FDIC data (likely a mid-tier holding company). FFIEC NIC relationship data would resolve these but its bulk
  download blocks automated access.

## 6. Duplicates and related entities

* RSSD appearing on more than one Treasury row: {dup.cdfi_id.nunique()} rows
  ({'; '.join(dup.cdfi_name)}). Both rows are kept (Treasury counts both); they share one NCUA charter.
* CDFIs sharing a website domain with another certified CDFI: {len(shared)} (mostly BHC + subsidiary bank pairs,
  and affiliated loan funds / credit unions such as Self-Help or HOPE). Field `shares_website_with`.
* Same normalized name + state appearing twice: {int(tl.dup_name_state_in_list.sum())}.
  Identical names in different states (e.g. "First State Bank" AR/MS) are distinct institutions with distinct RSSDs.

## 7. Lending focus (derived)

Banks/BHCs/credit unions: primary focus = largest standardized category share of total loans (category "other"
excluded). Loan/VC funds: evidence-based classification (IRS 990 text, SBA program lists, CDFI Fund award programs,
FHLB membership, names) - see `research/market_structure_report.md` and methodology section 13.

{md(focus)}

Primary-focus confidence (portfolio: HIGH ≥50% share, MEDIUM 30–50% and not a near-tie, LOW otherwise;
evidence: HIGH/MEDIUM/LOW per methodology; UNKNOWN = no usable evidence):

{md(conf)}

## 8. CDFI Fund awards linkage

* Award rows: {len(aw):,} (years {int(aw.award_year.min())}–{int(aw.award_year.max())}); linked to a certified CDFI:
  {linked.sum():,} rows covering {aw.loc[linked, 'cdfi_id'].nunique()} CDFIs.
* Unlinked rows are retained: they include BEA/NMTC recipients that are not CDFIs, decertified organizations and renamed entities.
* Award years 2023 and 2025 have far fewer rows than adjacent years ({(aw.award_year == 2023).sum()} and
  {(aw.award_year == 2025).sum()} rows vs {(aw.award_year == 2024).sum()} in 2024) — the export appears incomplete for recent rounds.

{md(aw_tab)}

## 9. Reporting periods

* FDIC and NCUA financials: **{m.financials_reporting_date.dropna().unique().tolist()}** (aligned quarter-end).
  Prior-year comparison: 2025-06-30. Growth is computed only where the same set of regulatory entities exists in both
  periods; growth still includes merger effects (e.g. FM Bank and Trust +142% assets after absorbing two banks in 2026).
* Net income is year-to-date (6 months) for both regulators.
* IRS BMF amounts: tax periods range {m.irs_tax_period.dropna().astype(int).min() if m.irs_tax_period.notna().any() else 'n/a'}–{m.irs_tax_period.dropna().astype(int).max() if m.irs_tax_period.notna().any() else 'n/a'} (YYYYMM); not aligned with the Call Report quarter.

## 10. Fields not available from public sources (left missing, not imputed)

* `certification_date`, target market, service area (collected by CDFI Fund, not released).
* Lending geography at institution level (CDFI Fund TLR/CLR are anonymized).
* Loan-fund lending composition; microenterprise / community facilities / venture flags for all types.
* Number of borrowers for banks (no Call Report field); members are available only for NCUA credit unions.
"""
    (RESEARCH / "data_quality_report.md").write_text(txt)
    cov.to_csv(PROCESSED.parent / "outputs" / "tables" / "coverage_by_type.csv", index=False)
    print(f"wrote {RESEARCH / 'data_quality_report.md'}")


if __name__ == "__main__":
    main()
